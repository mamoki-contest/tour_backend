package com.mamoki.tour.domain.visittiming.enums;

/**
 * 날짜 탐색 결과의 상태.
 *
 * <p>{@code DataStatus} 와 의미가 다르다. 그쪽은 공급자 데이터의 신선도(유효·최종 정상·정보 없음)를
 * 가리키고, 이쪽은 그 데이터로 이 장소·이 날짜를 판정할 수 있었는지를 가리킨다.
 * 데이터가 {@code AVAILABLE} 이어도 그 장소의 예측이 비어 있으면 {@link #NO_DATA} 가 된다.
 *
 * <p>등급 세 개는 모두 <b>같은 장소의 향후 30일 분포 안에서의 상대 수준</b>이다.
 * 서로 다른 관광지의 등급을 나란히 놓고 혼잡도 순위로 읽으면 안 된다.
 */
public enum VisitTimingStatus {

    /** 이 장소의 30일 분포에서 하위권. 상대적으로 한산하다. */
    LOW,

    /** 이 장소의 30일 분포에서 중간권. */
    NORMAL,

    /** 이 장소의 30일 분포에서 상위권. 상대적으로 혼잡하다. */
    HIGH,

    /** 예측이 없거나 판정에 필요한 만큼 모이지 않았다. 임의 값을 만들지 않는다. */
    NO_DATA,

    /** 선택일이 지원 범위(오늘부터 30일) 밖이다. 지원 범위를 함께 안내한다. */
    OUT_OF_RANGE
}
