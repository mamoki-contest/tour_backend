package com.mamoki.tour.domain.placeimage.enums;

/**
 * 한 관광지의 사진 보강이 어디까지 갔는지.
 *
 * <p>세 값이 모두 "행이 있다" 는 사실을 공유한다. 행이 없는 것은 <b>아직 묻지 않았다</b>는
 * 뜻이고, 다음 실행이 그 관광지를 대상으로 삼는다. 묻고 못 찾은 것과 아직 묻지 않은 것을
 * 같은 모양으로 두면, 결과가 없는 관광지를 매달 다시 물으며 하루 한도를 깎는다.
 */
public enum PlaceImageStatus {

    /** 쓸 수 있는 사진을 찾았다. 조회 응답이 이 행만 읽는다. */
    AVAILABLE,

    /** 공급자가 답했지만 쓸 수 있는 결과가 없었다. 0건이며 실패가 아니다. */
    NONE,

    /**
     * 이 관광지 하나의 호출·해석이 실패했다.
     *
     * <p>인증 실패나 한도 초과는 여기 담기지 않는다. 그 둘은 이 관광지의 문제가 아니라
     * 실행 전체의 문제라 배치가 그 자리에서 멈추고 아무 행도 남기지 않는다.
     */
    FAILED
}
