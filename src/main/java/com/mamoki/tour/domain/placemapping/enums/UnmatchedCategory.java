package com.mamoki.tour.domain.placemapping.enums;

/**
 * 카탈로그에 잇지 못한 이름이 왜 남았는지.
 *
 * <p>매칭률의 분모를 정리하려고 둔다. 원천 파일에는 관광공사 카탈로그가 애초에 담지 않는
 * 장소가 섞여 있어, 그것까지 분모에 넣으면 "얼마나 더 이을 수 있는가" 를 가늠할 수 없다.
 *
 * <p><b>{@link #OUT_OF_CATALOG} 만 분모에서 뺀다.</b> 그래서 이 값은 아껴 쓴다. 아닌 것을
 * 여기에 넣으면 분모가 줄어 매칭률이 올라가는데, 에러가 나지 않아 아무도 알아채지 못한다.
 * 개선과 분모 조작이 같은 숫자로 보인다. 확신이 서지 않으면 {@link #UNKNOWN} 이다.
 *
 * <p>확정({@code CONFIRMED})한 행에는 {@link #NAME_VARIANT} 만 붙는다. 표기 차이로
 * 되찾았다는 기록이다. 나머지 둘은 잇지 못한 행에만 뜻이 있다.
 */
public enum UnmatchedCategory {

    /**
     * 관광공사 카탈로그가 담는 종류가 아니다. 분모에서 뺀다.
     *
     * <p>카카오 카테고리와 이름 접미어가 <b>둘 다</b> 사전에 맞을 때만 붙인다. 게다가
     * 카탈로그에 그 종류가 실제로 들어 있으면 접미어 규칙 자체가 꺼진다.
     */
    OUT_OF_CATALOG,

    /**
     * 같은 장소를 카탈로그와 다르게 적었을 뿐이다.
     *
     * <p>괄호 안 별칭·시·군 접두어·공백만 걷어내면 카탈로그 이름과 같아진다. 그렇게 되찾은
     * 곳이 한 곳뿐이면 확정으로 올리고, 둘 이상이면 저신뢰로 남긴다.
     */
    NAME_VARIANT,

    /**
     * 어느 쪽인지 모른다. 분모에 그대로 둔다.
     *
     * <p>가장 많이 붙는 값이고 그래야 한다. 카탈로그에 없는 장소와 아직 규칙을 찾지 못한
     * 표기 차이가 여기 섞여 있다.
     */
    UNKNOWN
}
