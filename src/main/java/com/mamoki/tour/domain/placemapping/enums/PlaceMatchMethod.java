package com.mamoki.tour.domain.placemapping.enums;

/**
 * 매핑을 어떻게 판정했는지.
 *
 * <p>같은 {@code CONFIRMED} 라도 근거가 다르다. 나중에 잘못 이어진 행이 나왔을 때 어느
 * 근거가 약했는지 원천별로 되짚을 수 있어야 한다.
 */
public enum PlaceMatchMethod {

    /**
     * 카카오 대표 이름이 카탈로그 이름과 글자 그대로 같다.
     *
     * <p>원천 이름({@code 강릉 경포해변})이 카탈로그와 달라 매칭되지 않았는데, 카카오가
     * 돌려준 대표 이름이 카탈로그 이름과 완전히 같은 경우다.
     */
    EXACT,

    /** 카카오 대표 이름이 표기 정규화 후 카탈로그 이름과 같다. 공백·괄호·기호 차이만 있는 경우다. */
    NORMALIZED,

    /** 카카오가 준 좌표가 카탈로그 좌표의 거리 경계 안이고, 그 안에 후보가 한 곳뿐이다. */
    KAKAO_COORD,

    /**
     * 운영자가 직접 넣은 행.
     *
     * <p>배치가 덮지 않는다. 사람이 확인해 넣은 판단을 자동 판정이 되돌리면, 같은 행이
     * 실행할 때마다 왔다 갔다 하면서 아무도 알아채지 못한다.
     */
    MANUAL
}
